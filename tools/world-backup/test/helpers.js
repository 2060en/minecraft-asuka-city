// 測試用的小工具：產生 PNG 圖片、假的 uNmINeD 輸出。
import { deflateSync } from 'node:zlib';
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const CRC_TABLE = Array.from({ length: 256 }, (_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});

/** @param {Buffer} buf */
function crc32(buf) {
  let c = 0xffffffff;
  for (const byte of buf) c = CRC_TABLE[(c ^ byte) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

/** @param {string} type @param {Buffer} data */
function chunk(type, data) {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length);
  const body = Buffer.concat([Buffer.from(type, 'ascii'), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(body));
  return Buffer.concat([len, body, crc]);
}

/**
 * 產生一張單色（加上格線）的 PNG。
 * @param {number} size
 * @param {[number, number, number]} rgb
 */
export function solidPng(size, rgb) {
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(size, 0);
  ihdr.writeUInt32BE(size, 4);
  ihdr[8] = 8; // bit depth
  ihdr[9] = 2; // RGB
  const raw = Buffer.alloc((size * 3 + 1) * size);
  for (let y = 0; y < size; y++) {
    raw[y * (size * 3 + 1)] = 0;
    for (let x = 0; x < size; x++) {
      const edge = x === 0 || y === 0;
      const o = y * (size * 3 + 1) + 1 + x * 3;
      raw[o] = edge ? 0 : rgb[0];
      raw[o + 1] = edge ? 0 : rgb[1];
      raw[o + 2] = edge ? 0 : rgb[2];
    }
  }
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', ihdr),
    chunk('IDAT', deflateSync(raw)),
    chunk('IEND', Buffer.alloc(0)),
  ]);
}

/**
 * 寫一張 uNmINeD 格式的圖磚。
 * @param {string} renderDir
 * @param {number} zoom
 * @param {number} x
 * @param {number} y
 * @param {Buffer} png
 */
export function writeTile(renderDir, zoom, x, y, png) {
  const dir = join(renderDir, 'tiles', `zoom.${zoom}`, String(Math.floor(x / 10)), String(Math.floor(y / 10)));
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, `tile.${x}.${y}.png`), png);
}

/**
 * 寫 uNmINeD 的 unmined.map.properties.js。
 * @param {string} renderDir
 * @param {Record<string, unknown>} [overrides]
 */
export function writeProperties(renderDir, overrides = {}) {
  const p = {
    minZoom: -2, maxZoom: 1, defaultZoom: 0, imageFormat: 'png',
    minRegionX: -1, minRegionZ: -1, maxRegionX: 0, maxRegionZ: 0,
    worldName: 'Asuka World', background: '#000000', centerX: 0, centerZ: 0, ...overrides,
  };
  const body = Object.entries(p).map(([k, v]) => `    ${k}: ${typeof v === 'string' ? JSON.stringify(v) : v}`);
  body.splice(body.findIndex((l) => l.includes('background')) + 1, 0, '    markers: [],');
  mkdirSync(renderDir, { recursive: true });
  writeFileSync(join(renderDir, 'unmined.map.properties.js'), `/* Autogenerated file */\nvar UnminedMapProperties = {\n${body.join(',\n')}\n}\n`);
}
